#5 calcular a área de um triangulo
base = float(input("qual a base de seu triangulo:")) # variavel base solicitara o tamanho da base do triangulo
altura = float(input("qual a altura de seu triangulo:")) # variavel altura solicitara a altura do triangulo
area = (base * altura) / 2 # ira calcular a area multiplicando a base e a altura e dividindo por 2
print(area) # mostrara o resultado 
